import {createServer} from 'node:http';
import {readFile, stat, mkdir, writeFile} from 'node:fs/promises';
import {dirname, extname, resolve, sep} from 'node:path';
import {fileURLToPath} from 'node:url';
import assert from 'node:assert/strict';
import {chromium, expect} from '@playwright/test';

// Test the published static files with the exact Vercel headers and no API proxy.
const webRoot=resolve(dirname(fileURLToPath(import.meta.url)), '..');
const repository=resolve(webRoot,'../..');
const output=resolve(webRoot,'dist');
const remote=process.env.VELA_PUBLIC_URL;
const target=remote||'http://127.0.0.1:4173/';
const capture=process.env.VELA_CAPTURE_NAME||(remote?'vercel':'public');
assert(/^[a-z0-9-]+$/.test(capture),'Invalid capture name');
const screenshot='apps/web/artifacts/'+capture+'-simulation.png';
const report='artifacts/'+capture+'-browser-check.json';
const recordVideo=process.env.VELA_RECORD_VIDEO==='1';
const deployment=JSON.parse(await readFile(resolve(repository,'vercel.json'),'utf8'));
const mime={'.html':'text/html; charset=utf-8','.js':'text/javascript','.css':'text/css','.json':'application/json','.xml':'application/xml','.wasm':'application/wasm','.glb':'model/gltf-binary','.woff':'font/woff','.woff2':'font/woff2','.svg':'image/svg+xml'};
const server=createServer(async(request,response)=>{
  const pathname=decodeURIComponent(new URL(request.url,'http://localhost').pathname);
  const filename=resolve(output, pathname==='/'?'index.html':`.${pathname}`);
  for(const header of deployment.headers[0].headers)response.setHeader(header.key,header.value);
  if(!filename.startsWith(output+sep)){response.writeHead(403).end();return}
  try{
    const information=await stat(filename);
    if(!information.isFile())throw new Error('Not a file');
    response.writeHead(200,{'Content-Type':mime[extname(filename)]||'application/octet-stream'});
    response.end(await readFile(filename));
  }catch{response.writeHead(404,{'Content-Type':'text/plain'}).end('Not found')}
});
if(!remote)await new Promise(resolveReady=>server.listen(4173,'127.0.0.1',resolveReady));
const started=Date.now();
const errors=[],failedRequests=[],apiRequests=[];
const sceneAssetRequests=new Map();
let browser,page;
try{
  await mkdir(resolve(webRoot,'artifacts'),{recursive:true});
  browser=await chromium.launch({channel:'chrome',headless:true});
  const context=await browser.newContext({viewport:{width:1600,height:1000},...(recordVideo?{recordVideo:{dir:resolve(webRoot,'artifacts/video'),size:{width:1600,height:1000}}}:{})});
  page=await context.newPage();
  page.on('pageerror',error=>errors.push(String(error)));
  page.on('console',message=>{if(message.type()==='error')errors.push(message.text())});
  page.on('requestfailed',request=>failedRequests.push({url:request.url(),error:request.failure()?.errorText}));
  page.on('request',request=>{const url=new URL(request.url());if(url.pathname.startsWith('/api/'))apiRequests.push(request.url());if(url.pathname.startsWith('/simulation/'))sceneAssetRequests.set(url.pathname,url.searchParams.get('v'))});
  const navigation=await page.goto(target,{waitUntil:'networkidle'});
  assert.equal(navigation.status(),200,'Public page was not accessible');
  const contentSecurityPolicy=navigation.headers()['content-security-policy'];
  assert(contentSecurityPolicy?.includes("'wasm-unsafe-eval'"),'Missing WASM policy');
  assert(contentSecurityPolicy?.includes("'unsafe-eval'"),'Missing official MuJoCo embind policy');
  await expect.poll(async()=>{
    const alerts=await page.getByRole('alert').allTextContents();
    if(alerts.length)throw new Error(alerts.join('; '));
    return page.getByRole('button',{name:'Joint movement',exact:true}).isEnabled();
  },{timeout:60000}).toBe(true);
  await expect(page.getByText('MuJoCo · in browser',{exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Model & physics',exact:true}).click();
  await expect(page.getByText('28 synchronized',{exact:true})).toBeVisible();
  await page.getByText('25 joint positions',{exact:true}).click();
  const jointPositions=()=>page.locator('.immersive-joints code').allTextContents();
  const clock=async()=>parseFloat(await page.locator('.immersive-clock strong').innerText());
  const initial=await jointPositions();
  await page.getByRole('button',{name:'Joint movement',exact:true}).click();
  await page.waitForTimeout(3500);
  const moved=await jointPositions();
  const movingJoints=moved.filter((value,index)=>value!==initial[index]).length;
  assert(movingJoints>=20,`Only ${movingJoints} joints changed`);
  const movingTime=await clock();
  await page.getByRole('button',{name:'Pause simulation',exact:true}).click();
  await page.waitForTimeout(400);
  const pausedTime=await clock();
  await page.waitForTimeout(700);
  assert.equal(await clock(),pausedTime,'Simulation continued while paused');
  await page.getByRole('button',{name:'Reset simulation',exact:true}).click();
  await page.getByRole('button',{name:'Table reach demo',exact:true}).click();
  await page.waitForTimeout(6500);
  const reachErrorText=await page.locator('dl div').filter({has:page.getByText('Reach endpoint error',{exact:true})}).locator('dd').innerText();
  assert(parseFloat(reachErrorText)<.6,`Reach did not settle: ${reachErrorText}`);
  const physicsSteps=await page.locator('dl div').filter({has:page.getByText('Physics steps',{exact:true})}).locator('dd').innerText();
  await page.getByRole('button',{name:'Model & physics',exact:true}).click();
  console.log('Joint motion, pause and endpoint reach passed. Checking vertical travel.');
  await page.getByRole('button',{name:'Reset simulation',exact:true}).click();
  await page.getByRole('button',{name:'Vertical travel',exact:true}).click();
  const liftPanel=page.getByTestId('lift-metrics');
  await expect.poll(async()=>Number(await liftPanel.getAttribute('data-low-height')),{timeout:30000}).toBeLessThan(.15);
  await page.screenshot({path:resolve(webRoot,`artifacts/${capture}-vertical-low.png`)});
  await expect.poll(async()=>Number(await liftPanel.getAttribute('data-high-height')),{timeout:40000}).toBeGreaterThan(1.70);
  await page.screenshot({path:resolve(webRoot,`artifacts/${capture}-vertical-high.png`)});
  await expect(liftPanel).toHaveAttribute('data-complete','true',{timeout:30000});
  const vertical=await liftPanel.evaluate(element=>({complete:element.dataset.complete==='true',left_travel_m:Number(element.dataset.leftTravel),right_travel_m:Number(element.dataset.rightTravel),lowest_hand_height_m:Number(element.dataset.lowHeight),highest_hand_height_m:Number(element.dataset.highHeight)}));
  assert(vertical.left_travel_m>.83&&vertical.right_travel_m>.83);
  console.log('Vertical travel passed. Checking contact pickup and sustained hold.');
  await page.getByRole('button',{name:'Reset simulation',exact:true}).click();
  await page.getByRole('button',{name:'Pick up phone',exact:true}).click();
  const pickupPanel=page.getByTestId('pickup-metrics');
  await expect(pickupPanel).toHaveAttribute('data-success','true',{timeout:60000});
  await page.waitForTimeout(2500);
  const pickup=await pickupPanel.evaluate(element=>({success:element.dataset.success==='true',height_gain_m:Number(element.dataset.heightGain),bilateral_contact:element.dataset.bilateralContact==='true',bilateral_hold_seconds:Number(element.dataset.holdSeconds)}));
  assert(pickup.success&&pickup.bilateral_contact&&pickup.height_gain_m>.20&&pickup.bilateral_hold_seconds>=2);
  await expect(page.getByRole('button',{name:'Joint movement',exact:true})).toBeDisabled();
  await expect(page.getByText('Reset to switch',{exact:true})).toBeVisible();
  await page.screenshot({path:resolve(webRoot,`artifacts/${capture}-pickup.png`)});
  await page.getByRole('button',{name:'Release phone',exact:true}).click();
  await expect(pickupPanel).toHaveAttribute('data-released','true',{timeout:12000});
  const release=await pickupPanel.evaluate(element=>({released:element.dataset.released==='true',success:element.dataset.success==='true',height_gain_m:Number(element.dataset.heightGain)}));
  assert(release.released&&!release.success&&release.height_gain_m<.03);
  console.log('Actual contact pickup and gravity-driven release passed.');
  await page.getByRole('button',{name:'About this demo',exact:true}).click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await page.keyboard.press('Escape');
  await expect(page.getByRole('dialog')).not.toBeVisible();
  await expect(page.getByRole('button',{name:'About this demo',exact:true})).toBeFocused();
  await page.evaluate(()=>{location.hash='#staff'});
  await expect(page.getByRole('heading',{name:'Patient room 417.'})).toBeVisible();
  await page.getByRole('button',{name:'At the bedside',exact:true}).click();
  await page.waitForTimeout(600);
  await mkdir(resolve(webRoot,'artifacts'),{recursive:true});
  await page.screenshot({path:resolve(repository,screenshot)});
  assert.deepEqual(errors,[],'Browser errors');
  assert.deepEqual(failedRequests,[],'Failed network requests');
  assert.deepEqual(apiRequests,[],'Public demo called the local API');
  assert.equal(sceneAssetRequests.size,5,'Expected three GLBs and two physics fixtures');
  const revisions=new Set(sceneAssetRequests.values());assert.equal(revisions.size,1,'Scene assets have mismatched revisions');assert.match([...revisions][0],/^[a-f0-9]{16}$/);
  let videoPath;
  if(recordVideo){const video=page.video();await context.close();videoPath=`apps/web/artifacts/${capture}-motion.webm`;await video.saveAs(resolve(repository,videoPath));await video.delete()}
  const result={checked_at:new Date().toISOString(),elapsed_seconds:(Date.now()-started)/1000,origin:new URL(target).origin,server:remote?'Vercel production; anonymous Chrome context':'Static files with Vercel response headers; no API proxy',content_security_policy:contentSecurityPolicy,engine:'MuJoCo WebAssembly',viewport:{width:1600,height:1000},synchronized_bodies:28,joint_positions:initial.length,moving_joints:movingJoints,moving_simulation_time_seconds:movingTime,paused_simulation_time_seconds:pausedTime,reach_endpoint_error_display:reachErrorText,physics_steps_display:physicsSteps,vertical,pickup,release,scene_revision:[...revisions][0],default_route_3d:true,legacy_hash_stays_in_public_demo:true,about_dialog_escape_and_focus_restoration:true,errors,failed_requests:failedRequests,api_requests:apiRequests,screenshot,pickup_screenshot:`apps/web/artifacts/${capture}-pickup.png`,vertical_low_screenshot:`apps/web/artifacts/${capture}-vertical-low.png`,vertical_high_screenshot:`apps/web/artifacts/${capture}-vertical-high.png`,...(videoPath?{video:videoPath}:{})};
  await writeFile(resolve(repository,report),JSON.stringify(result,null,2)+'\n');
  console.log(JSON.stringify(result,null,2));
}catch(error){
  console.error(JSON.stringify({errors,failedRequests,apiRequests,alerts:await page?.getByRole('alert').allTextContents()},null,2));
  throw error;
}finally{
  await browser?.close();
  if(!remote)await new Promise(resolveClosed=>server.close(resolveClosed));
}
